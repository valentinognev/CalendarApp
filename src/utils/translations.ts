export const getTranslations = (lang: string) => {
    console.log('[Debug] getTranslations language:', lang);
    const target = TRANSLATIONS[lang];
    if (!target) console.warn('[Debug] Missing translation for:', lang);

    // Default to EN if not found
    const effectiveTarget = target || TRANSLATIONS['en'];
    const fallback = TRANSLATIONS['en'];

    return new Proxy(effectiveTarget, {
        get(obj, prop: string) {
            const val = obj[prop] || fallback[prop];
            if (!val && prop !== 'then') { // Ignore promise checks
                // console.warn(`[Debug] Missing key '${prop}' for lang '${lang}'`);
            }
            return val || prop;
        }
    });
};
